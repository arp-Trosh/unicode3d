"""Bitmap fonts for 3D lettering (shapes.text_mesh, text_bitmap): signs, titles, banners.

A font is {character: rows of "#" (ink) and "." (blank)}, every glyph the font's full height; glyphs may differ in
width. Draw your own in the same form (more rows look smoother, at the cost of triangles).

PIXEL: every printable ASCII character, 9 rows: capitals and digits on rows 0-6, lower case with its x-height on
rows 2-6, and descenders (g, j, p, q, y, the comma) on rows 7-8. Most glyphs are 5 wide; i, l, punctuation and
the space are narrower.
"""


def font(height, glyphs, top=0):
    """A font from compact glyphs: {character: rows joined by "/"} placed from row `top`, or (top, rows) for a
    glyph placed from a row of its own, each padded with blank rows to `height`."""
    out = {}
    for ch, spec in glyphs.items():
        at, spec = spec if isinstance(spec, tuple) else (top, spec)
        rows = spec.split("/")
        width = len(rows[0])
        if any(len(r) != width for r in rows) or at + len(rows) > height:
            raise ValueError(f"glyph {ch!r}: rows of different widths, or more than {height} rows")
        out[ch] = ["." * width] * at + rows + ["." * width] * (height - at - len(rows))
    return out


